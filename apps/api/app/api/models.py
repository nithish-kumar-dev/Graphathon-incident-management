"""API contracts (Pydantic v2). Requests forbid unknown fields and bound every string and number.
Responses carry real graph ids and relationship names; nothing here is generated by an LLM."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Literal

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

from app.ids import IncidentId, ServiceId

Severity = Literal["sev1", "sev2", "sev3", "sev4"]
IncidentStatus = Literal["open", "investigating", "mitigated", "resolved"]
AlertSeverity = Literal["critical", "warning", "info"]
Mode = Literal["recommendation_only", "simulation"]
InvestigationStatus = Literal["queued", "running", "awaiting_review", "completed", "failed", "escalated",
                              "inconclusive", "timed_out"]
BranchName = Literal["graph_context", "memory_context", "telemetry_context"]
BranchStatus = Literal["pending", "running", "completed", "failed", "skipped", "not_recorded"]
ClaimType = Literal["observed", "correlated", "hypothesis", "confirmed"]
DataClassification = Literal["synthetic"]


def to_dt(ms: int | None) -> datetime | None:
    return None if ms is None else datetime.fromtimestamp(ms / 1000, UTC)


class _In(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class _Out(BaseModel):
    model_config = ConfigDict(extra="forbid")


# ---------------------------------------------------------------- shared refs
class ServiceRef(_Out):
    id: str
    name: str | None = None
    tier: str | None = None


class EvidenceRef(_Out):
    id: str
    kind: str
    source_ref: str
    observed_at: datetime | None = None
    excerpt: str | None = None


class ResponderRef(_Out):
    id: str
    handle: str
    roles: list[str] = []


class DocumentRef(_Out):
    id: str
    title: str | None = None
    uri: str | None = None
    doc_type: str | None = None


class PathHop(_Out):
    """One real edge in the graph, in its stored direction."""
    from_label: str
    from_id: str
    rel: str
    to_label: str
    to_id: str


# ---------------------------------------------------------------------- alerts
class AlertIn(_In):
    fingerprint: str = Field(pattern=r"^[a-z0-9][a-z0-9_.:-]{2,127}$", examples=["checkout:http_5xx_rate"],
                             description="Stable identity of the alert rule + target; dedup key.")
    service_id: ServiceId
    severity: AlertSeverity
    fired_at: AwareDatetime = Field(description="When the alert fired (timezone required; stored as UTC ms).")
    summary: str = Field(min_length=1, max_length=500)
    source_ref: str = Field(pattern=r"^[a-z][a-z0-9+.-]{1,31}://\S{1,480}$", max_length=512,
                            examples=["synthetic://alerts/101-c"],
                            description="Unique reference of this alert event; ingest is idempotent on it.")


class AlertIngestResult(_Out):
    outcome: Literal["created_incident", "attached_to_incident", "deduplicated", "replayed"]
    alert_id: str
    incident_id: str | None
    incident_key: str | None
    dedup_count: int
    dedup_window_seconds: int


class AlertOut(_Out):
    id: str
    fingerprint: str
    severity: str
    fired_at: datetime
    last_fired_at: datetime | None = None
    dedup_count: int = 0
    summary: str | None = None
    source_ref: str | None = None


# ------------------------------------------------------------------- incidents
class IncidentSummary(_Out):
    id: str
    key: str
    title: str
    severity: Severity
    status: IncidentStatus
    started_at: datetime
    resolved_at: datetime | None = None
    affected_service_ids: list[str]
    alert_count: int
    data_classification: DataClassification = "synthetic"


class IncidentList(_Out):
    items: list[IncidentSummary]
    limit: int
    offset: int


class EvidenceOut(EvidenceRef):
    observed_on_service_ids: list[str]
    refers_to_deployment_ids: list[str]


class DeploymentRef(_Out):
    id: str
    version: str
    deployed_at: datetime
    status: str | None = None
    source_ref: str | None = None


class DecisionRef(_Out):
    id: str
    title: str
    status: str
    required_approver_role: str | None = None
    documented_in: list[DocumentRef] = []


class RunbookRef(_Out):
    id: str
    title: str
    version: str
    uri: str | None = None
    allowed_action_types: list[str] = []


class ExplanationPath(_Out):
    """Graph-derived correlation. It is evidence for a hypothesis, never a confirmed cause."""
    kind: Literal["rollback_candidate"] = "rollback_candidate"
    claim_type: Literal["correlated"] = "correlated"
    summary: str
    hops: list[PathHop]
    target_service_id: str
    deployment: DeploymentRef
    evidence: list[EvidenceRef]
    governing_decisions: list[DecisionRef]
    runbooks: list[RunbookRef]
    approval_policy: Literal["policy_in_force", "no_active_policy_escalate"]


class IncidentDetail(IncidentSummary):
    affected_services: list[ServiceRef]
    alerts: list[AlertOut]
    evidence: list[EvidenceOut]
    explanation_paths: list[ExplanationPath]
    as_of: datetime


class IncidentUpdate(_In):
    status: IncidentStatus | None = None
    severity: Severity | None = None

    @model_validator(mode="after")
    def _non_empty(self):
        if self.status is None and self.severity is None:
            raise ValueError("provide status and/or severity")
        return self


class TimelineEventOut(_Out):
    id: str
    at: datetime
    type: str
    actor: str | None = None
    summary: str | None = None
    ref_id: str | None = None


class IncidentTimeline(_Out):
    incident_id: str
    events: list[TimelineEventOut]


class MemoryOut(_Out):
    id: str
    memory_type: Literal["episodic", "procedural"]
    verification_status: Literal["draft", "verified", "rejected", "superseded"]
    outcome: Literal["successful", "failed", "unknown"]
    precedent: Literal["supports", "warns_against", "none"] = Field(
        description="supports = verified success; warns_against = verified failure; none = not verified.")
    summary: str
    about_incident_id: str
    about_incident_key: str | None
    relation: Literal["same_incident", "shared_service"]
    shared_service_ids: list[str]
    grounded_in: list[EvidenceRef]
    validated_by: list[ResponderRef]
    derived_from_action_ids: list[str]
    provenance_refs: list[str]
    validated_at: datetime | None = None
    validation_method: Literal["human", "ground_truth"] | None = None
    model_version: str | None = None


class IncidentMemories(_Out):
    incident_id: str
    include_unverified: bool
    memories: list[MemoryOut]


# -------------------------------------------------------------------- services
class TeamOut(_Out):
    id: str
    name: str
    members: list[ResponderRef]


class DependencyOut(_Out):
    service: ServiceRef
    depth: int
    path: list[str] = Field(description="Service ids along DEPENDS_ON, in stored edge direction.")
    rel: Literal["DEPENDS_ON"] = "DEPENDS_ON"


class DecisionOut(_Out):
    id: str
    title: str
    statement: str
    status: str
    effective_from: datetime
    effective_to: datetime | None = None
    required_approver_role: str | None = None
    documented_in: list[DocumentRef]
    supersedes: list[str]


class ServiceContext(_Out):
    service: ServiceRef
    owners: list[TeamOut]
    dependencies: list[DependencyOut]
    dependents: list[DependencyOut]
    active_decisions: list[DecisionOut]
    runbooks: list[RunbookRef]
    recent_deployments: list[DeploymentRef]
    depth: int
    as_of: datetime
    data_classification: DataClassification = "synthetic"


# --------------------------------------------------------------- investigations
class InvestigationIn(_In):
    incident_id: IncidentId
    mode: Mode = "recommendation_only"


class BranchState(_Out):
    status: BranchStatus
    detail: str | None = None
    started_at: datetime | None = Field(default=None, description="From the run's AgentEvent rows; null for runs that "
                                                                  "predate them")
    ended_at: datetime | None = None


class FindingOut(_Out):
    claim_type: ClaimType
    statement: str
    evidence: list[EvidenceRef] = Field(description="Supporting evidence (ids that exist in the graph only).")
    contradicting_evidence: list[EvidenceRef] = []
    confidence: float | None = Field(default=None, ge=0.0, le=1.0)
    uncertainty: str | None = None
    integrity_warnings: list[str] = []


GateDecision = Literal["accept", "revise", "recommendation_only", "escalate", "inconclusive"]


class ViolationOut(_Out):
    code: str
    target: str
    detail: str


class GateOut(_Out):
    """The evidence/safety gate's final decision for the run, with every violation it recorded."""
    decision: GateDecision
    violations: list[ViolationOut] = []


ReviewDecision = Literal["APPROVE", "REJECT", "REQUEST_REVISION", "ESCALATE"]


class ReviewIn(_In):
    decision: ReviewDecision
    comment: str | None = Field(default=None, max_length=1000)


class ReviewOut(_Out):
    """An ApprovalRecord HAS_REVIEW on an AgentAction. An APPROVE is bound to one spec hash and version."""
    id: str
    decision: ReviewDecision
    approver_id: str
    approver_handle: str | None = None
    decided_at: datetime
    expires_at: datetime | None = None
    comment: str | None = None
    spec_hash: str
    action_version: int
    policy_decision_id: str | None = None


class ExecutionOut(_Out):
    """Outcome of a SIMULATED execution. Nothing here touched a real system."""
    simulated: Literal[True] = True
    result: Literal["succeeded", "failed"]
    ticket: str | None = None
    executed_at: datetime
    note: str | None = None


class ProposedActionOut(_Out):
    """An AgentAction PART_OF the investigation. Actions are only ever executed in simulation, after a valid
    human APPROVE."""
    id: str
    proposal_id: str
    version: int
    action_type: str
    status: str
    mode: Mode
    target_service_id: str
    deployment_id: str | None = None
    runbook_id: str | None = None
    risk: str | None = None
    rationale: str | None = None
    spec: dict
    spec_hash: str
    evidence: list[EvidenceRef]
    required_approver_role: str | None = Field(default=None, description="From the active Decision governing the "
                                                                         "target service; null = no policy (fail closed)")
    approval_policy_id: str | None = None
    reviews: list[ReviewOut] = []
    execution: ExecutionOut | None = None
    integrity_warnings: list[str] = []


class ReviewResult(_Out):
    action: ProposedActionOut
    review: ReviewOut
    investigation_status: InvestigationStatus
    memory_id: str | None = Field(default=None, description="Draft memory written after a simulated execution; "
                                                            "excluded from retrieval until a human validates it")
    message: str


class InvestigationSummary(_Out):
    id: str
    mode: Mode
    status: InvestigationStatus
    requested_by: str | None = None
    started_at: datetime
    ended_at: datetime | None = None
    revision_count: int = 0
    investigator: str | None = None
    summary: str | None = None
    error: str | None = None


class InvestigationList(_Out):
    incident_id: str
    items: list[InvestigationSummary]


